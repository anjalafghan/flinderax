    ('CatCafe.dc.html', 'catcafe', 'cat café', 1, 'A paw-shaped card from Cat Café Studio, with a ginger cat asleep on it', (40, 10, 515, 590), 'Wake the cat', 'Let her sleep'),
    ('BlueTokaiFirst.dc.html', 'tokai1', 'blue tokai', 1, 'A Blue Tokai takeaway cup marked Diya + 1', (186, 90, 228, 472), 'Lift the lid', 'Put it back'),
    ('BlueTokaiRegulars.dc.html', 'tokai2', 'blue tokai', 2, 'A coffee-bean punch card from Blue Tokai and half a sandwich tied in red and green', (10, 10, 600, 560), 'Punch the card', 'Turn it back'),
