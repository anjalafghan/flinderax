def scope(css, cls, sfx):
    names = re.findall(r'@keyframes\s+([\w-]+)', css)
    def rename(body):
        for nm in names:
            body = re.sub(rf'(?<![\w-]){nm}(?![\w-])', nm + sfx, body)
        return body
    def rules(css):
        res = []
        for pre, body in split_blocks(css):
            if pre.startswith('@keyframes'):
                res.append(f'{rename(pre)}{{{body}}}')
            elif pre.startswith('@media'):
                res.append(f'{pre}{{{rules(body)}}}')
            else:
                sels = []
                for s in pre.split(','):
                    s = s.strip()
                    sels.append(f'.joy .{cls}.open' + s[5:] if s.startswith('.open') else f'.joy .{cls} {s}')
                res.append(','.join(sels) + '{' + rename(body) + '}')
        return '\n'.join(res)
    return rules(css)


FONTS = [
    ('Caveat', 400, 'normal', 'caveat-latin-400-normal'), ('Caveat', 600, 'normal', 'caveat-latin-600-normal'), ('Caveat', 700, 'normal', 'caveat-latin-700-normal'),
    ('Kalam', 400, 'normal', 'kalam-latin-400-normal'), ('Kalam', 700, 'normal', 'kalam-latin-700-normal'),
    ('Gochi Hand', 400, 'normal', 'gochi-hand-latin-400-normal'),
    ('Permanent Marker', 400, 'normal', 'permanent-marker-latin-400-normal'),
    ('Young Serif', 400, 'normal', 'young-serif-latin-400-normal'),
    ('Shippori Mincho', 600, 'normal', 'shippori-mincho-latin-600-normal'), ('Shippori Mincho', 800, 'normal', 'shippori-mincho-latin-800-normal'),
    ('Space Mono', 400, 'normal', 'space-mono-latin-400-normal'), ('Space Mono', 700, 'normal', 'space-mono-latin-700-normal'),
    ('Fraunces', '100 900', 'normal', 'fraunces-latin-full-normal'), ('Fraunces', '100 900', 'italic', 'fraunces-latin-full-italic'),
]

css_out = ['/* Generated by the keepsake boards (Design canvas "Month Page Scrapbook"): do not edit by hand.',
           '   Each scene\'s motion, scoped to .ksc-<id>; .open plays it. Fonts are self-hosted (OFL, from @fontsource). */']
for fam, w, st, f in FONTS:
    css_out.append(f'@font-face {{ font-family: "{fam}"; font-style: {st}; font-weight: {w}; font-display: swap; src: url("../fonts/{f}.woff2") format("woff2"); }}')

ts = ['// Generated from the keepsake boards on the Design canvas: do not edit by hand (see scenes.css).',
      '// Each scene is one kept date\'s own illustrated object; `svg` is static markup we drew, never user text.',
      'import type { SceneDef } from "./scene-types";', '', 'export const SCENES: SceneDef[] = [']
for board, sid, key, visit, name, vb, opened, closed in SCENES:
    kw = CAPTURED[board]
    svg = scope_ids(kw['svg'], sid + '-')
    svg = re.sub(r'<!--.*?-->', '', svg, flags=re.S)
    svg = re.sub(r'\n\s*\n', '\n', svg).strip()
    css_out.append(f'/* {sid} */')
    css_out.append(scope(kw['css'], f'ksc-{sid}', '_' + sid))
    ts.append('  {')
    ts.append(f'    id: {json.dumps(sid)}, key: {json.dumps(key)}, visit: {visit},')
    ts.append(f'    name: {json.dumps(name)},')
    ts.append(f'    vb: [{", ".join(map(str, vb))}], open: {json.dumps(opened)}, close: {json.dumps(closed)},')
    ts.append(f'    svg: {json.dumps(svg, ensure_ascii=False)},')
    ts.append('  },')
ts.append('];')

open(os.path.join(WEB, 'keepsakes', 'scenes.gen.ts'), 'w').write('\n'.join(ts) + '\n')
open(os.path.join(WEB, 'styles', 'scenes.css'), 'w').write('\n'.join(css_out) + '\n')
print('ok')
